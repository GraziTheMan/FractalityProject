// src/data/turtle.js
//
// Turtle (RDF) import and export for mind maps.
//
// These maps are concept hierarchies with labels, types and tags, which is what
// RDF is for — so exporting them as Turtle makes them readable by tools nobody
// here wrote, and lets one person's map be merged with another's.
//
// This is an INTERCHANGE format, deliberately alongside the JSON export rather
// than replacing it. JSON stays the wire format between browser and API and the
// shape the rest of the code and its tests are built on. Two specific reasons,
// not general caution:
//
//   1. RDF has no inherent ordering. `:a skos:narrower :b, :c` is a SET, and
//      sibling order is authoritative here — the Node Manager can reorder
//      siblings, so a naive translation would silently lose that. Order is
//      carried explicitly in `fract:position`.
//   2. Transient visual state (positions, colours) is recomputed by the layout
//      engine every frame. It is not ontology and is not exported; a re-imported
//      map is laid out afresh.
//
// Vocabulary: SKOS, not OWL. `skos:broader`/`skos:narrower` are deliberately
// vague about whether a child is a subclass, a part, or simply a narrower idea —
// which is what a mind map actually means. OWL's `subClassOf` would force that
// decision on every edge, and it would be the wrong one about half the time.
//
// N3 is loaded lazily. It is only needed when someone actually imports or
// exports, so it must not sit in the initial bundle.

import { NodeData, NodeGraph } from './NodeData.js';

export const NS = {
    skos: 'http://www.w3.org/2004/02/skos/core#',
    dcterms: 'http://purl.org/dc/terms/',
    fract: 'https://fractiverse.com/ns#',
    xsd: 'http://www.w3.org/2001/XMLSchema#',
    rdf: 'http://www.w3.org/1999/02/22-rdf-syntax-ns#',
};

/** Metadata keys that have a real vocabulary term, so they are not re-emitted as fract:*. */
const MAPPED_METADATA = new Set(['label', 'type', 'tags', 'description']);

/**
 * Metadata keys that exist only at runtime and must not round-trip.
 *
 * `created` and `modified` are regenerated by NodeData's constructor, so
 * exporting them would make a round trip look lossy when it is not.
 */
const TRANSIENT_METADATA = new Set(['created', 'modified', 'lastVisited', 'position', 'visual']);

/** Only these characters are safe in a bare fract: predicate name. */
const SAFE_KEY = /^[A-Za-z][A-Za-z0-9_-]*$/;

let n3Promise = null;

/**
 * Load N3 once, on first use.
 *
 * Cached as the promise rather than the module, so two rapid calls share one
 * network fetch instead of racing.
 */
function loadN3() {
    if (!n3Promise) n3Promise = import('n3');
    return n3Promise;
}

/** A node id turned into an IRI fragment, reversibly. */
function idToIri(base, id) {
    return `${base}${encodeURIComponent(id)}`;
}

/** The inverse. Returns null for an IRI that is not one of ours. */
function iriToId(base, iri) {
    if (!iri.startsWith(base)) return null;
    try {
        return decodeURIComponent(iri.slice(base.length));
    } catch {
        // A malformed percent-escape is not ours to interpret.
        return null;
    }
}

/**
 * Serialise a NodeGraph as Turtle.
 *
 * @param {NodeGraph} graph
 * @param {object} [options]
 * @param {string} [options.title]  becomes dcterms:title on the scheme
 * @param {string} [options.mapId]  used to build the base IRI
 * @returns {Promise<string>}
 */
export async function graphToTurtle(graph, { title = 'Untitled map', mapId = 'map' } = {}) {
    const { Writer, DataFactory } = await loadN3();
    const { namedNode, literal, quad } = DataFactory;

    const base = `https://fractiverse.com/map/${encodeURIComponent(mapId)}#`;
    const scheme = namedNode(`https://fractiverse.com/map/${encodeURIComponent(mapId)}`);

    const integer = (value) => literal(String(value), namedNode(`${NS.xsd}integer`));
    const double = (value) => literal(String(value), namedNode(`${NS.xsd}double`));
    const boolean = (value) => literal(value ? 'true' : 'false', namedNode(`${NS.xsd}boolean`));
    const skos = (term) => namedNode(NS.skos + term);
    const fract = (term) => namedNode(NS.fract + term);

    const quads = [];
    const add = (s, p, o) => quads.push(quad(s, p, o));

    // --- the map itself
    add(scheme, namedNode(`${NS.rdf}type`), skos('ConceptScheme'));
    add(scheme, namedNode(`${NS.dcterms}title`), literal(title));

    const roots = graph.getRootNodes();
    for (const root of roots) {
        add(scheme, skos('hasTopConcept'), namedNode(idToIri(base, root.id)));
    }

    // --- the concepts
    for (const node of graph.nodes.values()) {
        const subject = namedNode(idToIri(base, node.id));
        const metadata = node.metadata ?? {};

        add(subject, namedNode(`${NS.rdf}type`), skos('Concept'));
        add(subject, skos('prefLabel'), literal(metadata.label || node.id));
        add(subject, fract('tier'), integer(node.depth));

        if (metadata.description) {
            add(subject, namedNode(`${NS.dcterms}description`), literal(String(metadata.description)));
        }
        if (metadata.type) {
            add(subject, fract('nodeType'), literal(String(metadata.type)));
        }
        for (const tag of metadata.tags ?? []) {
            // Not skos:altLabel: a tag is not another name for the concept.
            add(subject, fract('tag'), literal(String(tag)));
        }

        // --- structure
        if (node.parentId && graph.nodes.has(node.parentId)) {
            const parent = graph.nodes.get(node.parentId);
            add(subject, skos('broader'), namedNode(idToIri(base, node.parentId)));

            // The position that makes the sibling ORDER survive. Without this the
            // narrower/broader pair is a set and the order is gone.
            const index = parent.childIds.indexOf(node.id);
            if (index >= 0) add(subject, fract('position'), integer(index));
        } else {
            add(subject, skos('topConceptOf'), scheme);
        }

        // Emitted as well as broader, for readers that only follow one direction.
        // On import, broader wins and this is ignored — see turtleToGraph.
        for (const childId of node.childIds) {
            if (graph.nodes.has(childId)) {
                add(subject, skos('narrower'), namedNode(idToIri(base, childId)));
            }
        }

        // --- anything else flat, so the round trip does not quietly drop it
        for (const [key, value] of Object.entries(metadata)) {
            if (MAPPED_METADATA.has(key) || TRANSIENT_METADATA.has(key)) continue;
            if (!SAFE_KEY.test(key)) continue;
            if (value === null || value === undefined) continue;

            // Datatypes matter here: an untyped literal is xsd:string, so 0.5
            // came back from a round trip as "0.5" and true as "true".
            if (typeof value === 'number' && Number.isInteger(value)) {
                add(subject, fract(key), integer(value));
            } else if (typeof value === 'number' && Number.isFinite(value)) {
                add(subject, fract(key), double(value));
            } else if (typeof value === 'boolean') {
                add(subject, fract(key), boolean(value));
            } else if (typeof value === 'string') {
                add(subject, fract(key), literal(value));
            }
            // NaN and Infinity are dropped: xsd has spellings for them, but a
            // mind map carrying one is a bug upstream, not data to preserve.
            // Nested objects and arrays other than tags are skipped: expressing
            // them properly needs their own vocabulary, and inventing one here
            // would produce output nobody else could read either.
        }
    }

    const writer = new Writer({
        prefixes: {
            skos: NS.skos,
            dcterms: NS.dcterms,
            fract: NS.fract,
            // Declared so typed literals read as `xsd:double` rather than
            // carrying the full datatype IRI inline.
            xsd: NS.xsd,
            '': base,
        },
    });
    for (const q of quads) writer.addQuad(q);

    return new Promise((resolve, reject) => {
        writer.end((error, result) => (error ? reject(error) : resolve(result)));
    });
}

/**
 * Parse Turtle into a NodeGraph.
 *
 * Tolerant on purpose: this may be handed a file another tool wrote, so it reads
 * what it recognises rather than demanding a shape. Anything with a
 * `skos:prefLabel` or a `skos:broader`/`narrower` edge becomes a node.
 *
 * @param {string} text
 * @returns {Promise<{graph: NodeGraph, title: string|null, warnings: string[]}>}
 */
export async function turtleToGraph(text) {
    const { Parser } = await loadN3();
    const warnings = [];

    const parser = new Parser({ baseIRI: 'https://fractiverse.com/map/imported' });
    let quads;
    try {
        quads = parser.parse(text);
    } catch (error) {
        throw new Error(`That is not valid Turtle: ${error.message}`);
    }
    if (quads.length === 0) throw new Error('The file contains no RDF statements');

    /** iri -> collected fields */
    const found = new Map();
    const ensure = (iri) => {
        if (!found.has(iri)) {
            found.set(iri, {
                iri, label: null, description: null, type: null,
                tags: [], tier: null, position: null,
                parentIri: null, childIris: [], extra: {}, isTopConcept: false,
            });
        }
        return found.get(iri);
    };

    let title = null;

    for (const q of quads) {
        const s = q.subject.value;
        const p = q.predicate.value;
        const o = q.object;

        if (p === `${NS.dcterms}title`) { title = o.value; continue; }

        if (p === `${NS.skos}prefLabel`) { ensure(s).label = o.value; continue; }
        if (p === `${NS.dcterms}description`) { ensure(s).description = o.value; continue; }
        if (p === `${NS.fract}nodeType`) { ensure(s).type = o.value; continue; }
        if (p === `${NS.fract}tag`) { ensure(s).tags.push(o.value); continue; }
        if (p === `${NS.fract}tier`) { ensure(s).tier = _int(o.value); continue; }
        if (p === `${NS.fract}position`) { ensure(s).position = _int(o.value); continue; }

        if (p === `${NS.skos}broader`) { ensure(s).parentIri = o.value; ensure(o.value); continue; }
        if (p === `${NS.skos}narrower`) { ensure(s).childIris.push(o.value); ensure(o.value); continue; }
        if (p === `${NS.skos}topConceptOf`) { ensure(s).isTopConcept = true; continue; }
        if (p === `${NS.skos}hasTopConcept`) { ensure(o.value).isTopConcept = true; continue; }

        if (p === `${NS.rdf}type` && o.value === `${NS.skos}Concept`) { ensure(s); continue; }

        // Unrecognised fract:* predicates go back into metadata, so a field this
        // version does not know about survives a round trip through it.
        if (p.startsWith(NS.fract)) {
            const key = p.slice(NS.fract.length);
            if (SAFE_KEY.test(key)) ensure(s).extra[key] = _coerce(o);
        }
    }

    if (found.size === 0) {
        throw new Error('No SKOS concepts found. Is this a mind map?');
    }

    // The base is whatever the CONCEPTS use, not what we would have written: an
    // imported file may come from a different map or another tool.
    //
    // Inferred from the concepts alone, deliberately. Including every subject let
    // the ConceptScheme's own IRI in, which is the base minus its trailing '#' —
    // so the common prefix collapsed back to ".../map/" and every id came out as
    // "test#alpha" instead of "alpha".
    const base = _inferBase([...found.keys()]);

    // --- ids
    const idFor = new Map();
    const usedIds = new Set();
    for (const iri of found.keys()) {
        let id = base ? iriToId(base, iri) : null;
        if (!id) {
            // Foreign IRI: fall back to its fragment or last path segment, which
            // is what a human would call it.
            id = decodeURIComponent(iri.split('#').pop().split('/').pop() || iri);
        }
        if (!id) id = iri;

        let unique = id;
        let n = 2;
        while (usedIds.has(unique)) unique = `${id}-${n++}`;
        if (unique !== id) {
            warnings.push(`Two concepts resolved to the id "${id}"; renamed one to "${unique}".`);
        }
        usedIds.add(unique);
        idFor.set(iri, unique);
    }

    // --- build
    const graph = new NodeGraph();
    for (const entry of found.values()) {
        const id = idFor.get(entry.iri);
        const node = new NodeData(id, entry.tier ?? 0, {
            label: entry.label || id,
            type: entry.type || 'default',
            tags: entry.tags,
            ...(entry.description ? { description: entry.description } : {}),
            ...entry.extra,
        });
        graph.nodes.set(id, node);
    }

    // Parents from skos:broader, which is authoritative. narrower is only used to
    // fill gaps, because a file may state one direction and not the other; taking
    // both as equal would let them contradict each other.
    for (const entry of found.values()) {
        const id = idFor.get(entry.iri);
        const node = graph.nodes.get(id);
        if (entry.parentIri && idFor.has(entry.parentIri)) {
            node.parentId = idFor.get(entry.parentIri);
        }
    }
    for (const entry of found.values()) {
        const parentId = idFor.get(entry.iri);
        for (const childIri of entry.childIris) {
            const childId = idFor.get(childIri);
            const child = graph.nodes.get(childId);
            if (child && !child.parentId) child.parentId = parentId;
        }
    }

    // --- childIds, in fract:position order
    const positionOf = new Map();
    for (const entry of found.values()) {
        positionOf.set(idFor.get(entry.iri), entry.position);
    }

    for (const node of graph.nodes.values()) {
        const children = [...graph.nodes.values()].filter((n) => n.parentId === node.id);
        children.sort((a, b) => {
            const pa = positionOf.get(a.id);
            const pb = positionOf.get(b.id);
            // Nodes without a position keep a stable order by label, so an
            // imported file from another tool is at least deterministic.
            if (pa === null && pb === null) {
                return String(a.metadata.label).localeCompare(String(b.metadata.label));
            }
            if (pa === null) return 1;
            if (pb === null) return -1;
            return pa - pb;
        });
        node.childIds = children.map((c) => c.id);
    }

    // Break any cycle a hand-edited file might describe, before it reaches code
    // that assumes a tree.
    const detached = _breakCycles(graph);
    for (const id of detached) {
        warnings.push(`"${id}" was part of a cycle; detached it to the top tier.`);
    }

    // Recompute every tier from the parent links. fract:tier is a hint, and a
    // file that disagrees with itself should not produce a graph that does.
    graph.rebuildIndices();

    return { graph, title, warnings };
}

function _int(value) {
    const n = Number.parseInt(value, 10);
    return Number.isFinite(n) ? n : null;
}

/** Turn a literal back into the JS type its datatype implies. */
function _coerce(term) {
    const datatype = term.datatype?.value ?? '';
    if (datatype === `${NS.xsd}integer`) return _int(term.value) ?? term.value;
    if (datatype === `${NS.xsd}boolean`) return term.value === 'true';
    if (datatype === `${NS.xsd}double` || datatype === `${NS.xsd}decimal`) {
        const n = Number.parseFloat(term.value);
        return Number.isFinite(n) ? n : term.value;
    }
    return term.value;
}

/**
 * Work out the base IRI the concepts share, so ids can be recovered.
 *
 * The longest common prefix up to and including the last '#' or '/'.
 *
 * @param {string[]} iris concept IRIs only — see the caller for why
 */
function _inferBase(iris) {
    const subjects = iris.filter((iri) => typeof iri === 'string' && iri.includes(':'));
    if (subjects.length === 0) return null;

    let prefix = subjects[0];
    for (const iri of subjects.slice(1)) {
        let i = 0;
        while (i < prefix.length && i < iri.length && prefix[i] === iri[i]) i++;
        prefix = prefix.slice(0, i);
        if (!prefix) return null;
    }

    const cut = Math.max(prefix.lastIndexOf('#'), prefix.lastIndexOf('/'));
    return cut >= 0 ? prefix.slice(0, cut + 1) : null;
}

/**
 * Detach any node that is its own ancestor.
 *
 * Turtle can describe a cycle perfectly legally, and the layout engine and the
 * Node Manager both assume a tree. Better to detach and say so than to hand a
 * cyclic graph to code that will loop on it.
 *
 * @returns {string[]} ids that were detached
 */
function _breakCycles(graph) {
    const detached = [];
    for (const node of graph.nodes.values()) {
        const seen = new Set([node.id]);
        let current = node;
        while (current.parentId) {
            if (seen.has(current.parentId)) {
                const parent = graph.nodes.get(current.parentId);
                if (parent) {
                    parent.childIds = parent.childIds.filter((id) => id !== current.id);
                }
                current.parentId = null;
                detached.push(current.id);
                break;
            }
            seen.add(current.parentId);
            const next = graph.nodes.get(current.parentId);
            if (!next) { current.parentId = null; break; }
            current = next;
        }
    }
    return detached;
}
